"""Committed generator examples, with opt-in updates and read-only checks."""

from pathlib import Path

import pytest
from linkml.generators.erdiagramgen import ERDiagramGenerator

from linkml_gdscript.generator import GDScriptGenerator

SCHEMA = """id: https://example.org/golden
name: sample
classes:
  Record: {}
"""
SOURCE = b"""# Generated by linkml-gdscript from schema "sample". Do not edit.
class_name LinkMLRecord
extends RefCounted
"""
DIAGRAM = b"```mermaid\nerDiagram\nRecord {\n\n}\n\n\n\n```\n"


def golden_files(root: Path) -> dict[Path, bytes]:
    """Read GDScript and Markdown expectations, not ownership metadata."""
    paths = [*root.rglob("*.gd"), *root.rglob("*.md")]
    return {path.relative_to(root): path.read_bytes() for path in paths}


def sync_goldens(inputs: Path, goldens: Path, generated: Path, *, update: bool = False) -> None:
    """Compare freshly generated files, or explicitly accept their complete set."""
    schemas = sorted([*inputs.glob("*.yaml"), *inputs.glob("*.yml")])
    assert schemas, f"No golden input schemas found in {inputs}"
    assert len({schema.stem for schema in schemas}) == len(schemas), "Duplicate golden input stems"
    for schema in schemas:
        directory = generated / schema.stem
        GDScriptGenerator(str(schema)).serialize(directory=directory)
        diagram = ERDiagramGenerator(str(schema), format="markdown", structural=False).serialize()
        (directory / "README.md").write_text(
            "\n".join(line.rstrip() for line in diagram.splitlines()) + "\n", encoding="utf-8"
        )
    actual, expected = golden_files(generated), golden_files(goldens)
    if update:
        for obsolete in expected.keys() - actual.keys():
            (goldens / obsolete).unlink()
        for name, data in actual.items():
            target = goldens / name
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(data)
        return
    command = "nix develop --command golden --update-goldens"
    assert expected.keys() == actual.keys(), f"Golden filenames differ; review updates with `{command}`"
    for name in sorted(actual):
        assert expected[name] == actual[name], f"Golden content differs: {name}; review updates with `{command}`"


def test_committed_goldens(tmp_path: Path, request: pytest.FixtureRequest) -> None:
    """Every input has exactly the committed GDScript and schema diagram output."""
    root = Path(__file__).resolve().parent
    sync_goldens(root / "input", root / "golden", tmp_path, update=request.config.getoption("--update-goldens"))


@pytest.fixture
def golden_case(tmp_path: Path) -> tuple[Path, Path]:
    """A real minimal schema and its independently specified golden source."""
    inputs, goldens = tmp_path / "input", tmp_path / "golden"
    inputs.mkdir()
    (inputs / "sample.yaml").write_text(SCHEMA, encoding="utf-8")
    (goldens / "sample").mkdir(parents=True)
    (goldens / "sample/link_ml_record.gd").write_bytes(SOURCE)
    (goldens / "sample/README.md").write_bytes(DIAGRAM)
    return inputs, goldens


@pytest.mark.parametrize("filename", ["link_ml_record.gd", "README.md"])
@pytest.mark.parametrize("drift", ["changed", "missing", "added", "orphaned"])
def test_check_rejects_drift_without_writing(
    golden_case: tuple[Path, Path], tmp_path: Path, drift: str, filename: str
) -> None:
    """Content and inventory drift must fail without accepting or repairing it."""
    inputs, goldens = golden_case
    target = goldens / "sample" / filename
    if drift == "changed":
        target.write_bytes(target.read_bytes() + b"# drift\n")
    elif drift == "missing":
        target.unlink()
    elif drift == "added":
        (target.parent / f"extra{target.suffix}").write_bytes(b"# extra\n")
    else:
        (goldens / "retired").mkdir()
        (goldens / "retired" / f"obsolete{target.suffix}").write_bytes(b"# obsolete\n")
    before = golden_files(goldens)
    with pytest.raises(AssertionError, match="Golden"):
        sync_goldens(inputs, goldens, tmp_path / "generated")
    assert golden_files(goldens) == before


def test_update_discovers_inputs_and_retires_obsolete_files(golden_case: tuple[Path, Path], tmp_path: Path) -> None:
    """Explicit updates replace contents, add fixtures, and remove stale expectations."""
    inputs, goldens = golden_case
    (inputs / "other.yml").write_text(SCHEMA.replace("sample", "other"), encoding="utf-8")
    (goldens / "sample/link_ml_record.gd").write_bytes(b"# old policy\n")
    (goldens / "retired").mkdir()
    (goldens / "retired/obsolete.gd").write_bytes(b"# obsolete\n")
    (goldens / "retired/README.md").write_bytes(b"# obsolete diagram\n")
    sentinel = goldens.parent / "keep.txt"
    sentinel.write_bytes(b"outside goldens\n")
    sync_goldens(inputs, goldens, tmp_path / "generated", update=True)
    assert golden_files(goldens) == {
        Path("sample/link_ml_record.gd"): SOURCE,
        Path("sample/README.md"): DIAGRAM,
        Path("other/link_ml_record.gd"): SOURCE.replace(b'"sample"', b'"other"'),
        Path("other/README.md"): DIAGRAM,
    }
    assert not list(goldens.rglob("*.json"))
    assert sentinel.read_bytes() == b"outside goldens\n"
    sync_goldens(inputs, goldens, tmp_path / "rechecked")


def test_failed_generation_does_not_update_goldens(golden_case: tuple[Path, Path], tmp_path: Path) -> None:
    """A later invalid fixture cannot leave earlier expectations partially refreshed."""
    inputs, goldens = golden_case
    (inputs / "zz_bad.yaml").write_text(
        SCHEMA.replace("Record: {}", "Record:\n    attributes:\n      bad: {range: Missing}"), encoding="utf-8"
    )
    (goldens / "sample/link_ml_record.gd").write_bytes(b"# preserve on failure\n")
    (goldens / "sample/README.md").write_bytes(b"# preserve diagram on failure\n")
    before = golden_files(goldens)
    with pytest.raises(ValueError, match='No such type: "Missing"'):
        sync_goldens(inputs, goldens, tmp_path / "generated", update=True)
    assert golden_files(goldens) == before


@pytest.mark.parametrize("duplicate", [False, True], ids=["empty-input", "duplicate-stem"])
def test_ambiguous_inputs_do_not_update_goldens(
    golden_case: tuple[Path, Path], tmp_path: Path, duplicate: bool
) -> None:
    """Empty discovery and colliding YAML stems must not erase or merge expectations."""
    inputs, goldens = golden_case
    if duplicate:
        (inputs / "sample.yml").write_text(SCHEMA, encoding="utf-8")
    else:
        (inputs / "sample.yaml").unlink()
    before = golden_files(goldens)
    with pytest.raises(AssertionError, match="input"):
        sync_goldens(inputs, goldens, tmp_path / "generated", update=True)
    assert golden_files(goldens) == before


def test_diagram_uses_clean_markdown_lines(golden_case: tuple[Path, Path], tmp_path: Path) -> None:
    """Upstream attribute padding must not introduce trailing whitespace in Git."""
    inputs, goldens = golden_case
    (inputs / "sample.yaml").write_text(
        SCHEMA.replace("classes:", "imports: [linkml:types]\nclasses:").replace(
            "Record: {}", "Record:\n    attributes:\n      label: {range: string}"
        ),
        encoding="utf-8",
    )
    sync_goldens(inputs, goldens, tmp_path / "generated", update=True)
    diagram = (goldens / "sample/README.md").read_text(encoding="utf-8")
    assert "    string label\n" in diagram
    assert all(line == line.rstrip() for line in diagram.splitlines())


def test_one_diagram_includes_classes_outside_tree_root(golden_case: tuple[Path, Path], tmp_path: Path) -> None:
    """A root must not hide disconnected classes from the schema's single graph."""
    inputs, goldens = golden_case
    (inputs / "sample.yaml").write_text(
        SCHEMA.replace("Record: {}", "Root: {tree_root: true}\n  Detached: {}"), encoding="utf-8"
    )
    sync_goldens(inputs, goldens, tmp_path / "generated", update=True)
    readme = goldens / "sample/README.md"
    diagram = readme.read_text(encoding="utf-8")
    assert "Root {\n" in diagram
    assert "Detached {\n" in diagram
    assert diagram.count("```mermaid\n") == 1
    assert list(readme.parent.glob("*.md")) == [readme]
